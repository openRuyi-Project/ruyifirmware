"""Generate JTAG recovery addresses from the release layout and coreboot ELF."""
import argparse
from pathlib import Path
import subprocess
import sys

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'tools'))
from image_layout import FU740_RECOVERY, STAGE_LAYOUTS


def main():
    parser = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    commands = parser.add_subparsers(dest='board', required=True)
    for board in ('unmatched', 'p550'):
        cmd = commands.add_parser(board, allow_abbrev=False)
        cmd.add_argument('--output', type=Path, required=True)
        cmd.add_argument('--rom', type=Path, required=True)
        if board == 'unmatched':
            cmd.add_argument('--bootblock', type=Path, required=True)
            cmd.add_argument('--nm', required=True)
    args = parser.parse_args()
    if args.board == 'unmatched':
        prefix = 'fu740'
        values = dict(FU740_RECOVERY)
        symbols = {}
        for line in subprocess.check_output([args.nm, str(args.bootblock)], text=True).splitlines():
            fields = line.split()
            if len(fields) == 3:
                symbols[fields[2]] = int(fields[0], 16)
        values['ddr_ready'] = symbols['cbmem_initialize_empty']
        if (symbols['_bootblock'] != values['lim_base'] or
                symbols['_ebootblock'] - symbols['_bootblock'] > values['bootblock_limit'] or
                not values['lim_base'] <= values['ddr_ready'] < values['lim_base'] + values['bootblock_limit']):
            raise ValueError('coreboot bootblock differs from the recovery layout')
    else:
        prefix = 'eic7700'
        layout = STAGE_LAYOUTS[args.board]
        values = dict(rom_address=layout.mcpu_address, rom_size=layout.coreboot_bytes,
                      wait_address=layout.wait_address)
    if args.rom.stat().st_size != values['rom_size']:
        raise ValueError('coreboot image size differs from the recovery layout')
    args.output.write_text('# Generated by recovery-layout.py.\n' + ''.join(
        f'set {prefix}_{name} 0x{value:x}\n' for name, value in values.items()))


if __name__ == '__main__':
    main()
