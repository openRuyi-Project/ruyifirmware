/*
 * Inline ECC changes ECCCFG0 and ADDRMAP registers. Substitute values
 * in place so that enabling ECC retains the original programming order.
 * Columns follow enum ddr_memory_profile: LPDDR4X, LPDDR5 16/32 GiB.
 */
static const struct {
	u32 offset;
	u32 value[3];
} ecc_settings[] = {
	{0x10600, {0x063f7f44, 0x063f7f44, 0x063f7f44}}, /* ECCCFG0 */
	{0x30004, {0x3f3f3f04, 0x3f3f3f05, 0x3f3f3f05}}, /* ADDRMAP1 */
	{0x3000c, {0x00040404, 0x003f0404, 0x003f0404}}, /* ADDRMAP3 */
	{0x30014, {0x1f151515, 0x1f151515, 0x1f161616}}, /* ADDRMAP5 */
	{0x3001c, {0x1f050505, 0x1f1f0606, 0x1f060606}}, /* ADDRMAP7 */
	{0x30020, {0x05050505, 0x06060606, 0x06060606}}, /* ADDRMAP8 */
	{0x30024, {0x05050505, 0x06060606, 0x06060606}}, /* ADDRMAP9 */
	{0x30028, {0x05050505, 0x06060606, 0x06060606}}, /* ADDRMAP10 */
	{0x3002c, {0x00000505, 0x00000606, 0x00000606}}, /* ADDRMAP11 */
	{0x30010, {0x00003f3f, 0x00000606, 0x00000606}}, /* ADDRMAP4 */
	{0x30018, {0x00000000, 0x00000000, 0x00000000}}, /* ADDRMAP6 */
};

static u32 ecc_value(u32 offset, u32 value, enum ddr_memory_profile memory)
{
	for (unsigned int i = 0; i < sizeof(ecc_settings) / sizeof(ecc_settings[0]); i++)
		if (offset == ecc_settings[i].offset)
			return ecc_settings[i].value[memory];
	return value;
}

int ddr_configure_controllers(u32 controller0, enum ddr_memory_profile memory,
			      int ecc)
{
	unsigned int count;

	if ((unsigned int)memory > DDR_LPDDR5_32GB)
		return -1;
	if (memory == DDR_LPDDR4X)
		count = sizeof(lp4_settings) / sizeof(lp4_settings[0]);
	else
		count = sizeof(lp5_settings) / sizeof(lp5_settings[0]);

	for (unsigned int channel = 0; channel < 2; channel++) {
		u32 base = controller0 + channel * 0x80000U;

		for (unsigned int i = 0; i < count; i++) {
			u32 offset, value;

			if (memory == DDR_LPDDR4X) {
				offset = lp4_settings[i].offset;
				value = lp4_settings[i].value;
			} else {
				offset = lp5_settings[i].offset;
				value = memory == DDR_LPDDR5_16GB ?
					lp5_settings[i].value16 : lp5_settings[i].value32;
			}
			if (ecc)
				value = ecc_value(offset, value, memory);
			ddr_write32(base + offset, value);
		}
	}
	return 0;
}
